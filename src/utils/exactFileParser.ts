/**
 * SAM HASH VERIFY — Universal Manifest Parser & ExactFile Engine
 * Specially designed parser with isolated ExactFile 1.0.x format support,
 * GNU coreutils (sha256sum/md5sum), CSV, and SAM HASH VERIFY JSON/TXT formats.
 * 100% Client-side deterministic parsing without data modification.
 */

import { HashAlgorithm } from '../types';

export interface ExactFileMetadata {
  isExactFile: boolean;
  version?: string;
  declaredDate?: string;
  declaredCount?: number;
  recognizedCount: number;
  countMismatchWarning?: string;
  algorithms: HashAlgorithm[];
}

export interface ParsedManifestRecord {
  lineNumber: number;
  expectedHash: string;
  algorithm: HashAlgorithm;
  fileName: string;
  relativePath: string;
  rawLine: string;
  isValid: boolean;
  errorMessage?: string;
}

export type ManifestFormatType =
  | 'EXACTFILE'
  | 'SAM_HASH_VERIFY_JSON'
  | 'SAM_HASH_VERIFY_TXT'
  | 'CSV'
  | 'GNU_COREUTILS'
  | 'GENERIC_TXT';

export interface ParseManifestResult {
  format: ManifestFormatType;
  formatLabel: string;
  exactFileMeta?: ExactFileMetadata;
  records: ParsedManifestRecord[];
  validCount: number;
  invalidCount: number;
  algorithms: HashAlgorithm[];
  parseErrors: { line: number; message: string; rawText: string }[];
  headerComments: string[];
}

/**
 * Normalize algorithm string to standard HashAlgorithm
 */
export function normalizeAlgorithmName(raw: string): HashAlgorithm | null {
  const clean = raw.trim().toUpperCase().replace(/[-_]/g, '');
  if (clean === 'SHA256') return 'SHA-256';
  if (clean === 'MD5') return 'MD5';
  if (clean === 'SHA1') return 'SHA-1';
  if (clean === 'SHA512') return 'SHA-512';
  return null;
}

/**
 * Check if string is valid hex with exact length for algorithm
 */
export function validateHashFormat(hash: string, algorithm: HashAlgorithm): boolean {
  const trimmed = hash.trim();
  if (!/^[0-9a-fA-F]+$/.test(trimmed)) return false;

  const expectedLength: Record<HashAlgorithm, number> = {
    'MD5': 32,
    'SHA-1': 40,
    'SHA-256': 64,
    'SHA-512': 128,
  };

  return trimmed.length === expectedLength[algorithm];
}

/**
 * Dedicated ExactFile Parser
 */
export function parseExactFileManifest(content: string): ParseManifestResult {
  const lines = content.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');

  let version: string | undefined;
  let declaredDate: string | undefined;
  let declaredCount: number | undefined;

  const headerComments: string[] = [];
  const records: ParsedManifestRecord[] = [];
  const parseErrors: { line: number; message: string; rawText: string }[] = [];
  const algosFound = new Set<HashAlgorithm>();

  for (let idx = 0; idx < lines.length; idx++) {
    const lineNum = idx + 1;
    const rawLine = lines[idx];
    const trimmed = rawLine.trim();

    // 1. Skip completely empty lines
    if (!trimmed) continue;

    // 2. Comments starting with semicolon ;
    if (trimmed.startsWith(';')) {
      headerComments.push(trimmed);

      // Check for version: "; Checksums generated by ExactFile 1.0.0.15"
      const verMatch = trimmed.match(/;\s*Checksums\s+generated\s+by\s+ExactFile\s+([0-9\.]+)/i);
      if (verMatch) {
        version = verMatch[1];
        continue;
      }

      // Check for date: "; 21/10/2026 16:15:41"
      const dateMatch = trimmed.match(/;\s*(\d{1,2}[\/\-\.]\d{1,2}[\/\-\.]\d{2,4}\s+\d{1,2}:\d{2}(?::\d{2})?)/);
      if (dateMatch) {
        declaredDate = dateMatch[1];
        continue;
      }

      // Check for footer count: "; 3 files hashed."
      const countMatch = trimmed.match(/;\s*(\d+)\s+files?\s+hashed/i);
      if (countMatch) {
        declaredCount = parseInt(countMatch[1], 10);
        continue;
      }

      continue;
    }

    // 3. ExactFile Record Line matching:
    // Pattern: <HASH> <marker>?<ALGO>[*]<FILENAME>
    // Note: filename can contain spaces, dots, dashes, parentheses, Unicode, accents.
    // Example: "635ca...dad6 ?SHA256HASH-BEM333.pdf"
    // Example: "5e12e...cc472 ?SHA256iOS Support Matrix - 7.79.3.pdf"
    // Example: "00375...5562 ?SHA256*IPJ_EXT_EXT_2026_0284.pdf"
    const exactFileRegex = /^([a-fA-F0-9]{32,128})\s+\?([A-Za-z0-9\-_]+)(\*|\s\*|\s)?(.*)$/;
    const match = trimmed.match(exactFileRegex);

    if (match) {
      const hashStr = match[1];
      const rawAlgoStr = match[2];
      let fileNameOrPath = match[4];

      // Handle edge cases where marker didn't have asterisk or space
      // If fileNameOrPath is empty but match[3] was captured, or trim leading space
      fileNameOrPath = fileNameOrPath.trim();

      const algo = normalizeAlgorithmName(rawAlgoStr) || 'SHA-256';
      algosFound.add(algo);

      const isValidHash = validateHashFormat(hashStr, algo);

      if (!isValidHash) {
        parseErrors.push({
          line: lineNum,
          message: `Hash com comprimento ou caracteres inválidos para o algoritmo ${algo} (${hashStr.length} caracteres).`,
          rawText: rawLine,
        });
      }

      if (!fileNameOrPath) {
        parseErrors.push({
          line: lineNum,
          message: 'Nome do arquivo não localizado após o marcador do algoritmo.',
          rawText: rawLine,
        });
      }

      const isValid = isValidHash && Boolean(fileNameOrPath);

      // Extract fileName from relative path if present
      const cleanPath = fileNameOrPath.replace(/\\/g, '/');
      const parts = cleanPath.split('/');
      const fileName = parts[parts.length - 1] || cleanPath;

      records.push({
        lineNumber: lineNum,
        expectedHash: hashStr,
        algorithm: algo,
        fileName,
        relativePath: cleanPath,
        rawLine,
        isValid,
        errorMessage: !isValid
          ? !isValidHash
            ? `Hash inválido para ${algo}`
            : 'Nome de arquivo ausente'
          : undefined,
      });
    } else {
      // Line is not a comment, not empty, but does not match ExactFile format
      parseErrors.push({
        line: lineNum,
        message: 'Linha não corresponde ao padrão de registro do ExactFile (<HASH> ?<ALGO>*<ARQUIVO>).',
        rawText: rawLine,
      });
      records.push({
        lineNumber: lineNum,
        expectedHash: '',
        algorithm: 'SHA-256',
        fileName: 'Registro Inválido',
        relativePath: '',
        rawLine,
        isValid: false,
        errorMessage: 'Formato de linha inválido',
      });
    }
  }

  const validCount = records.filter((r) => r.isValid).length;
  const invalidCount = records.length - validCount;

  let countMismatchWarning: string | undefined;
  if (declaredCount !== undefined && declaredCount !== validCount) {
    countMismatchWarning = `Atenção: O rodapé do ExactFile declarou ${declaredCount} arquivo(s), mas foram identificados ${validCount} registro(s) válido(s).`;
  }

  const exactFileMeta: ExactFileMetadata = {
    isExactFile: true,
    version,
    declaredDate,
    declaredCount,
    recognizedCount: validCount,
    countMismatchWarning,
    algorithms: Array.from(algosFound),
  };

  return {
    format: 'EXACTFILE',
    formatLabel: 'ExactFile (Checksums)',
    exactFileMeta,
    records,
    validCount,
    invalidCount,
    algorithms: Array.from(algosFound),
    parseErrors,
    headerComments,
  };
}

/**
 * Universal Auto-Detector and Parser for any supported manifest format
 */
export function detectAndParseManifest(content: string): ParseManifestResult {
  const trimmed = content.trim();

  // 1. Check for SAM HASH VERIFY JSON format
  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    try {
      const parsed = JSON.parse(trimmed);
      if (
        parsed.system?.includes('SAM HASH VERIFY') ||
        parsed.exportType === 'DIRECTORY_INTEGRITY_MANIFEST' ||
        Array.isArray(parsed.files)
      ) {
        const records: ParsedManifestRecord[] = (parsed.files || []).map(
          (f: any, idx: number) => {
            const algo: HashAlgorithm = parsed.algorithms?.[0] || 'SHA-256';
            const hash = f.hashes?.[algo] || f.hash || '';
            const relPath = (f.relativePath || f.fileName || '').replace(/\\/g, '/');
            const parts = relPath.split('/');
            const name = parts[parts.length - 1] || relPath;

            return {
              lineNumber: idx + 1,
              expectedHash: hash,
              algorithm: algo,
              fileName: name,
              relativePath: relPath,
              rawLine: JSON.stringify(f),
              isValid: Boolean(hash && relPath),
            };
          }
        );

        return {
          format: 'SAM_HASH_VERIFY_JSON',
          formatLabel: 'Manifesto SAM HASH VERIFY (JSON)',
          records,
          validCount: records.filter((r) => r.isValid).length,
          invalidCount: records.filter((r) => !r.isValid).length,
          algorithms: parsed.algorithms || ['SHA-256'],
          parseErrors: [],
          headerComments: [
            `Sistema: ${parsed.system || 'SAM HASH VERIFY'}`,
            `Protocolo: ${parsed.id || 'N/A'}`,
            `Data: ${parsed.timestamp || 'N/A'}`,
          ],
        };
      }
    } catch {
      // Not valid JSON, continue to other formats
    }
  }

  // 2. Check for ExactFile signature or markers
  const lines = trimmed.split(/\r?\n/);
  const isExactFileHeader = lines.some((l) => /;\s*Checksums\s+generated\s+by\s+ExactFile/i.test(l));
  const hasExactFileMarkers = lines.some((l) => /\s+\?(?:SHA256|MD5|SHA1|SHA512)/i.test(l));

  if (isExactFileHeader || hasExactFileMarkers) {
    return parseExactFileManifest(content);
  }

  // 3. Check for SAM HASH VERIFY Header in TXT
  if (content.includes('SAM HASH VERIFY — FORENSIC INTEGRITY SYSTEM') || content.includes('MANIFESTO DE INTEGRIDADE')) {
    const gnuParsed = parseGnuCoreutilsManifest(content);
    return {
      ...gnuParsed,
      format: 'SAM_HASH_VERIFY_TXT',
      formatLabel: 'Manifesto SAM HASH VERIFY (TXT)',
    };
  }

  // 4. Check for CSV (contains comma and header or multiple commas per line)
  const firstNonEmptyLines = lines.filter((l) => l.trim() && !l.trim().startsWith('#')).slice(0, 5);
  const isCSV = firstNonEmptyLines.some((l) => l.includes(',') && (l.includes('Arquivo') || l.includes('Hash') || l.includes('Caminho') || l.split(',').length >= 4));

  if (isCSV) {
    return parseCsvManifest(content);
  }

  // 5. Default to GNU Coreutils / Checksum style (<HASH>  *<FILE> or <HASH>  <FILE>)
  return parseGnuCoreutilsManifest(content);
}

/**
 * GNU coreutils parser (sha256sum, md5sum)
 */
export function parseGnuCoreutilsManifest(content: string): ParseManifestResult {
  const lines = content.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');
  const records: ParsedManifestRecord[] = [];
  const parseErrors: { line: number; message: string; rawText: string }[] = [];
  const algosFound = new Set<HashAlgorithm>();
  const headerComments: string[] = [];

  for (let idx = 0; idx < lines.length; idx++) {
    const lineNum = idx + 1;
    const rawLine = lines[idx];
    const trimmed = rawLine.trim();

    if (!trimmed) continue;
    if (trimmed.startsWith('#') || trimmed.startsWith('//') || trimmed.startsWith(';')) {
      headerComments.push(trimmed);
      continue;
    }

    // Match: <HASH> [* ]<PATH>
    const match = trimmed.match(/^([a-fA-F0-9]{32,128})\s+[\*]?(.+)$/);
    if (match) {
      const hashStr = match[1];
      const relPath = match[2].trim().replace(/\\/g, '/');

      let algo: HashAlgorithm = 'SHA-256';
      if (hashStr.length === 32) algo = 'MD5';
      else if (hashStr.length === 40) algo = 'SHA-1';
      else if (hashStr.length === 64) algo = 'SHA-256';
      else if (hashStr.length === 128) algo = 'SHA-512';

      algosFound.add(algo);

      const parts = relPath.split('/');
      const fileName = parts[parts.length - 1] || relPath;

      records.push({
        lineNumber: lineNum,
        expectedHash: hashStr,
        algorithm: algo,
        fileName,
        relativePath: relPath,
        rawLine,
        isValid: true,
      });
    } else {
      parseErrors.push({
        line: lineNum,
        message: 'Linha não reconhecida no padrão de checksum (<HASH> *<ARQUIVO>).',
        rawText: rawLine,
      });
    }
  }

  return {
    format: 'GNU_COREUTILS',
    formatLabel: 'Checksum GNU Coreutils (sha256sum / md5sum)',
    records,
    validCount: records.filter((r) => r.isValid).length,
    invalidCount: records.filter((r) => !r.isValid).length,
    algorithms: algosFound.size > 0 ? Array.from(algosFound) : ['SHA-256'],
    parseErrors,
    headerComments,
  };
}

/**
 * CSV Manifest Parser
 */
export function parseCsvManifest(content: string): ParseManifestResult {
  const lines = content.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');
  const records: ParsedManifestRecord[] = [];
  const parseErrors: { line: number; message: string; rawText: string }[] = [];
  const algosFound = new Set<HashAlgorithm>();
  const headerComments: string[] = [];

  for (let idx = 0; idx < lines.length; idx++) {
    const lineNum = idx + 1;
    const rawLine = lines[idx];
    const trimmed = rawLine.trim();

    if (!trimmed) continue;
    if (trimmed.startsWith('#') || trimmed.startsWith('//') || trimmed.startsWith(';')) {
      headerComments.push(trimmed);
      continue;
    }

    const parts = trimmed.split(',').map((p) => p.trim().replace(/^["']|["']$/g, ''));
    const firstUpper = parts[0].toUpperCase();

    // Skip CSV header line
    if (firstUpper === 'ARQUIVO' || firstUpper === 'FILENAME' || firstUpper === 'SEQUENCIAL') {
      headerComments.push(trimmed);
      continue;
    }

    // Detect column positions
    // Format A: Sequencial, Caminho_Relativo, Nome_Arquivo, Extensao, Tamanho, Algoritmo, Hash_Calculado
    // Format B: Arquivo, Caminho_Relativo, Tamanho_Bytes, Algoritmo, Hash_SHA256, Data_Hora
    // Format C: Hash, Caminho
    let hashStr = '';
    let relPath = '';
    let algo: HashAlgorithm = 'SHA-256';

    if (parts.length >= 7 && (parts[6].length === 64 || parts[6].length === 32)) {
      relPath = parts[1];
      algo = (normalizeAlgorithmName(parts[5]) as HashAlgorithm) || 'SHA-256';
      hashStr = parts[6];
    } else if (parts.length >= 5 && (parts[4].length === 64 || parts[4].length === 32)) {
      relPath = parts[1] || parts[0];
      algo = (normalizeAlgorithmName(parts[3]) as HashAlgorithm) || 'SHA-256';
      hashStr = parts[4];
    } else if (parts.length >= 2 && (parts[0].length === 64 || parts[0].length === 32)) {
      hashStr = parts[0];
      relPath = parts[1];
    } else if (parts.length >= 2 && (parts[1].length === 64 || parts[1].length === 32)) {
      relPath = parts[0];
      hashStr = parts[1];
    }

    if (hashStr && relPath) {
      if (hashStr.length === 32) algo = 'MD5';
      else if (hashStr.length === 40) algo = 'SHA-1';
      else if (hashStr.length === 64) algo = 'SHA-256';
      else if (hashStr.length === 128) algo = 'SHA-512';

      algosFound.add(algo);
      const cleanPath = relPath.replace(/\\/g, '/');
      const nameParts = cleanPath.split('/');
      const fileName = nameParts[nameParts.length - 1] || cleanPath;

      records.push({
        lineNumber: lineNum,
        expectedHash: hashStr,
        algorithm: algo,
        fileName,
        relativePath: cleanPath,
        rawLine,
        isValid: true,
      });
    } else {
      parseErrors.push({
        line: lineNum,
        message: 'Não foi possível identificar as colunas de caminho e hash na linha CSV.',
        rawText: rawLine,
      });
    }
  }

  return {
    format: 'CSV',
    formatLabel: 'Planilha CSV de Hashes',
    records,
    validCount: records.filter((r) => r.isValid).length,
    invalidCount: records.filter((r) => !r.isValid).length,
    algorithms: algosFound.size > 0 ? Array.from(algosFound) : ['SHA-256'],
    parseErrors,
    headerComments,
  };
}
